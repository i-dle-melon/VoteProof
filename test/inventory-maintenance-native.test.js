import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {randomBytes,randomUUID} from 'node:crypto';
import {unstable_splitSqlQuery} from 'wrangler';
import {localCaseRuntime} from '../scripts/lib/local-case-runtime.mjs';

test('real local workerd/D1/R2: maintenance-only segmented scan and atomic finalize keep normal mutation guards',async t=>{
 const local=await localCaseRuntime({submissionsEnabled:false,seedCampaign:false});t.after(()=>local.runtime.dispose());
 let db=local.db;const secret=randomBytes(32).toString('hex');
 await db.prepare('UPDATE storage_capacity SET used_bytes=153,inventory_count=51 WHERE id=1').run();
 const sql=fs.readFileSync('migrations-reset-v1/0001_reset_fence.sql','utf8');
 await db.batch(unstable_splitSqlQuery(sql).map(s=>db.prepare(s)));
 await db.prepare('INSERT INTO prelaunch_reset_schema_versions VALUES(1,?,?)').bind('19054e1e954a03456b7e93052cc3f051f79817380828f35f607ebb5231e04cbe',new Date().toISOString()).run();
 await db.prepare("UPDATE prelaunch_reset_control SET epoch=1,version=3,run_id=? WHERE id=1").bind(randomUUID()).run();
 for(let n=0;n<51;n++)await local.bucket.put('synthetic/'+String(n).padStart(3,'0'),new Uint8Array([1,2,3]));
 await local.setAuthConfig({PRELAUNCH_RESET_FENCE_ENABLED:'true',R2_EXCLUSIVE_WRITER_CONFIRMED:'true',GOOGLE_DRIVE_BACKUP_ENABLED:'true',DRIVE_BACKUP_RELAY_SECRET:secret});
 db=local.db;
 const headers={Authorization:'Bearer '+secret,'X-VoteProof-Reset-Epoch':'1'};
 const call=async(path,body)=>{const r=await local.fetch(path,'POST',body,headers);const b=await r.json();assert.equal(r.status,200,JSON.stringify(b));return b.data;};
 const path='/api/internal/drive-backup/storage/tick';
 const first=await call(path,{inventory_only:true});assert.equal(first.inventory.scanned,50);assert.equal(first.inventory.phase,'scan');
 assert.equal((await db.prepare('SELECT trusted_until FROM storage_capacity').first()).trusted_until,0);
 const ready=await call(path,{inventory_only:true});assert.equal(ready.inventory.scanned,51);assert.equal(ready.inventory.phase,'finalize');
 const done=await call('/api/internal/drive-backup/storage/inventory/finalize',{inventory_id:ready.inventory.inventory_id,inventory_version:ready.inventory.inventory_version});
 assert.equal(done.inventory.bytes,153);assert.equal(done.inventory.anomaly,null);assert.equal(done.inventory.complete,true);
 const cap=await db.prepare('SELECT * FROM storage_capacity').first();assert.equal(cap.inventory_id,null);assert.equal(cap.inventory_count,51);assert.equal(cap.trusted_until-cap.observed_at,600);
 assert.equal((await db.prepare("SELECT mode FROM prelaunch_reset_control").first()).mode,'maintenance');
 assert.equal((await db.prepare('SELECT submissions_enabled FROM submission_settings').first()).submissions_enabled,0);
 assert.equal((await db.prepare('SELECT COUNT(*) n FROM prelaunch_reset_permit').first()).n,0);
 assert.equal((await db.prepare("SELECT COUNT(*) n FROM prelaunch_reset_operations WHERE state!='completed'").first()).n,0);
 assert.equal((await db.prepare('SELECT COUNT(*) n FROM storage_audit').first()).n,1);
 assert.equal((await db.prepare('SELECT COUNT(*) n FROM storage_history').first()).n,1);
 await assert.rejects(db.prepare('UPDATE submission_settings SET submissions_enabled=1').run(),/PRELAUNCH_WRITE_FENCED/);
 await assert.rejects(db.prepare('UPDATE storage_capacity SET used_bytes=0').run(),/PRELAUNCH_WRITE_FENCED/);
 for(const url of ['/api/admin/storage/inventory','/api/internal/drive-backup/storage/archive','/api/uploads/prepare'])assert.equal((await local.fetch(url,'POST',{},headers)).status,503);
 assert.ok(await local.bucket.head('synthetic/000'));assert.ok(await local.bucket.head('synthetic/050'));
 assert.equal(local.unexpectedUpstreams.length,0);
});
